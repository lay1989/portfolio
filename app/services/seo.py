"""Consistent social image fallbacks for public pages and private previews."""

from flask import current_app, request


def social_metadata(page, brand_images, image_info, private=False):
    shared = brand_images.get("sharing")
    if shared and not page.get("entry_image"):
        origin = (
            request.host_url.rstrip("/") if private else current_app.config["SITE_URL"]
        )
        return {
            "url": origin + shared["url"],
            "width": shared["width"],
            "height": shared["height"],
            "alt": shared["alt"],
            "type": shared["type"],
        }
    origin = current_app.config["SITE_URL"]
    url = page.get("ogImage") or origin + "/public/images/og-image.png"
    info = image_info(url.removeprefix(origin))
    return {
        "url": url,
        "width": page.get("ogImageWidth") or (info["width"] if info else None),
        "height": page.get("ogImageHeight") or (info["height"] if info else None),
        "alt": page.get("ogImageAlt") or page.get("title", ""),
        "type": page.get("ogImageType")
        or (
            "image/png"
            if url.endswith(".png")
            else "image/jpeg"
            if url.endswith((".jpg", ".jpeg"))
            else "image/webp"
        ),
    }


COLLECTION_PAGES = {
    "project": ("projects", "Work", "/projects.html"),
    "post": ("blog", "Blog", "/blog.html"),
    "tool": ("tools", "Tools", "/tools.html"),
}
VISIBILITY_FIELD = {
    "key": "search_visibility",
    "label": "Search visibility",
    "group": "Search appearance",
    "type": "visibility",
    "limit": 7,
    "default": "index",
}


def indexed(payload):
    return payload.get("search_visibility", "index") != "noindex"


def same_content(before, after):
    """Placement IDs are regenerated by forms; they are not a content change."""

    def meaningful(value):
        if isinstance(value, dict):
            return {key: meaningful(item) for key, item in value.items() if key != "id"}
        if isinstance(value, list):
            return [meaningful(item) for item in value]
        return value

    return meaningful(before) == meaningful(after)


def iso_time(value):
    from datetime import UTC

    return value.replace(tzinfo=UTC).isoformat() if value else None


def entry_modified(entry, data, preview=False):
    modified = iso_time(entry.published_modified_at) if not preview else None
    # An editorial date can be in the future; do not claim an earlier update date.
    if modified and entry.kind == "post" and modified[:10] < data.get("date", ""):
        return None
    return modified


def site_entities(branding):
    root = current_app.config["SITE_URL"] + "/"
    person = {
        "@type": "Person",
        "@id": root + "#person",
        "name": branding["ownerName"],
        "url": root,
    }
    website = {
        "@type": "WebSite",
        "@id": root + "#website",
        "name": branding["ownerName"],
        "url": root,
        "publisher": {"@id": person["@id"]},
        "inLanguage": "en",
    }
    return root, person, website


def home_schema(page, branding, site):
    root, person, website = site_entities(branding)
    person["contactPoint"] = [
        {
            "@type": "ContactPoint",
            "email": site["email"],
            "contactType": "customer service",
        }
    ]
    profile = {
        "@type": "ProfilePage",
        "@id": root + "#webpage",
        "url": root,
        "name": page["title"],
        "description": page["description"],
        "inLanguage": "en",
        "isPartOf": {"@id": website["@id"]},
        "mainEntity": {"@id": person["@id"]},
    }
    return {"@context": "https://schema.org", "@graph": [website, person, profile]}


def collection_schema(page, branding, items):
    _, person, website = site_entities(branding)
    canonical = page["canonical"]
    listing = {
        "@type": "ItemList",
        "@id": canonical + "#items",
        "numberOfItems": len(items),
        "itemListElement": [
            {
                "@type": "ListItem",
                "position": i + 1,
                "name": entry.published["title"],
                "url": current_app.config["SITE_URL"] + entry.path,
            }
            for i, entry in enumerate(items)
        ],
    }
    collection = {
        "@type": "CollectionPage",
        "@id": canonical + "#webpage",
        "url": canonical,
        "name": page["title"],
        "description": page["description"],
        "inLanguage": "en",
        "isPartOf": {"@id": website["@id"]},
        "mainEntity": {"@id": listing["@id"]},
    }
    return {
        "@context": "https://schema.org",
        "@graph": [website, person, collection, listing],
    }


def entry_schema(page, entry, data, branding, cover=None, preview=False):
    root, person, website = site_entities(branding)
    canonical = page["canonical"]
    _, label, collection_path = COLLECTION_PAGES[entry.kind]
    breadcrumbs = [
        {"name": "Home", "url": root, "path": "/"},
        {
            "name": label,
            "url": current_app.config["SITE_URL"] + collection_path,
            "path": collection_path,
        },
        {"name": data["title"], "url": canonical, "path": entry.path},
    ]
    breadcrumb = {
        "@type": "BreadcrumbList",
        "@id": canonical + "#breadcrumbs",
        "itemListElement": [
            {
                "@type": "ListItem",
                "position": i + 1,
                "name": item["name"],
                "item": item["url"],
            }
            for i, item in enumerate(breadcrumbs)
        ],
    }
    work = {
        "@type": {
            "post": "BlogPosting",
            "project": "Article",
            "tool": "SoftwareApplication",
        }[entry.kind],
        "@id": canonical + "#content",
        "name": data["title"],
        "description": data.get("summary", ""),
        "url": canonical,
        "author": person,
        "mainEntityOfPage": {"@id": canonical + "#webpage"},
    }
    if entry.kind in ("post", "project"):
        work.update(
            headline=data["title"],
            articleSection=data.get("category", ""),
            publisher=person,
            inLanguage="en",
        )
    if entry.kind == "post":
        work["datePublished"] = data["date"]
    if entry.kind == "tool":
        work["applicationCategory"] = data.get("category", "")
        if data.get("launch_url"):
            work["url"] = data["launch_url"]
    if data.get("tags"):
        work["keywords"] = data["tags"]
    modified = entry_modified(entry, data, preview)
    if modified:
        work["dateModified"] = modified
    if cover:
        work["image"] = {
            "@type": "ImageObject",
            "url": cover["url"],
            "width": cover["width"],
            "height": cover["height"],
            "caption": cover.get("alt", ""),
        }
    webpage = {
        "@type": "WebPage",
        "@id": canonical + "#webpage",
        "url": canonical,
        "name": page["title"],
        "description": page["description"],
        "inLanguage": "en",
        "isPartOf": {"@id": website["@id"]},
        "breadcrumb": {"@id": breadcrumb["@id"]},
        "mainEntity": {"@id": work["@id"]},
    }
    return {
        "@context": "https://schema.org",
        "@graph": [website, person, webpage, work, breadcrumb],
    }, breadcrumbs


def sitemap_pages():
    if not current_app.config["SEARCH_INDEXING_ENABLED"]:
        return []
    from ..extensions import db
    from ..models import Entry
    from .collections import public_page_size
    from .pages import published_page

    pages = []
    if indexed(published_page("homepage")):
        pages.append(("/", None))
    for kind, (key, _, path) in COLLECTION_PAGES.items():
        if indexed(published_page(key)):
            count = db.session.scalar(
                db.select(db.func.count())
                .select_from(Entry)
                .where(Entry.kind == kind, Entry.published.is_not(None))
            )
            pages.extend(
                (path + (f"?page={number}" if number > 1 else ""), None)
                for number in range(
                    1,
                    max(
                        1,
                        (count + public_page_size(kind) - 1) // public_page_size(kind),
                    )
                    + 1,
                )
            )
    for path, modified, visibility in db.session.execute(
        db.select(
            Entry.path,
            Entry.published_modified_at,
            Entry.published["search_visibility"].as_string(),
        )
        .where(Entry.published.is_not(None))
        .order_by(Entry.path)
    ):
        if visibility != "noindex":
            pages.append((path, modified))
    return pages
